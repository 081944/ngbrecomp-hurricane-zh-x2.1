#!/usr/bin/env python3
"""Hurricane x2.1: sub_00212C20 (the items page's button hint) with the talisman hook inlined.

    python tools/hurricane/make_hint_212c20.py > src/hurricane_hint.c

The patch replaces `cmp ax,0xFB; je 0x212F10` at 0x212EFF (the talisman excluded from the hint)
with `jmp 0xDC84E0`; the hook then jumps back into the middle of this function (0x212F05, 0x212F10,
0x212F59). Lifted functions cannot jump into one another, so the lifter turned the jmp into a tail
call and the three targets into stubs, and the code at 0x212F05 lost its label. This takes the
lifted function from src/recomp/gen and the lifted hook (sub_00DC84E0), puts the hook's statements
in place of the tail call with its three exits as gotos, and gives 0x212F05 its label back.

Checked as it goes: the function differs from the retail lift only in that block (that is asserted
by the caller, docs/04), every replaced text is found exactly once, and no call to the stubs is left.
"""
import glob
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
gen = os.path.join(root, 'src', 'recomp', 'gen')


def lifted(name):
    for path in sorted(glob.glob(os.path.join(gen, 'recomp_*.c'))):
        m = re.search(r'/\*\*\n \* %s\n.*?\n\}\n' % name, open(path, encoding='utf-8').read(), re.S)
        if m:
            return m.group(0)
    sys.exit('%s not in the generated code (already taken?)' % name)


def once(text, old, new):
    assert text.count(old) == 1, (old, text.count(old))
    return text.replace(old, new)


func = lifted('sub_00212C20')
hook = lifted('sub_00DC84E0')

# the hook's statements: from its first label to its closing brace
body = hook[hook.index('loc_00DC84E0: ;'):hook.rindex('\n}\n')].rstrip() + '\n'
body = once(body, '{ g_seh_ebp = ebp; sub_00212F05(); return; } /* jne: not equal / not zero */',
            'goto loc_00212F05; /* jne: not the talisman -> as before */')
body = once(body, '{ g_seh_ebp = ebp; sub_00212F10(); return; } /* je: equal / zero */',
            'goto loc_00212F10; /* je: none in the bag -> "B Back" as the original */')
body = once(body, '{ g_seh_ebp = ebp; sub_00212F05(); return; } /* je: equal / zero */',
            'goto loc_00212F05; /* je: talisman off -> "X Select" */')
body = once(body, 'g_seh_ebp = ebp; sub_00212F59(); return; /* tail jmp 0x00212F59 */',
            'goto loc_00212F59; /* talisman on: hint 0x3A */')
assert 'sub_00212F' not in body, body

old = ('loc_00212EFF: ;\n'
       '    g_seh_ebp = ebp; sub_00DC84E0(); return; /* tail jmp 0x00DC84E0 */\n'
       '\n'
       '    /* nop */\n')
new = ('loc_00212EFF: ;\n'
       '    /* Hurricane x2.1 talisman_patch: the hook at 0xDC84E0 (jmp from here), inlined. */\n'
       + '\n'.join('    ' + l if l and not l.startswith('loc_') else l for l in body.splitlines()) + '\n'
       '\n'
       'loc_00212F05: ;\n')
func = once(func, old, new)
assert 'sub_00DC84E0' not in func.split('loc_00212EFF')[1]

sys.stdout.write('''/*
 * hurricane_hint.c -- the items page's button hint (sub_00212C20) for the Hurricane x2.1 build.
 *
 * Generated by tools/hurricane/make_hint_212c20.py from the lifted function and the lifted
 * talisman hook (0xDC84E0): the hook jumps back into the middle of this function, which lifted
 * functions cannot do, so its statements are inlined here and its exits are gotos. Listed in
 * src/manual_functions.json so the pipeline leaves the function out.
 */
#define RECOMP_GENERATED_CODE
#include "recomp_funcs.h"

''' + func)
