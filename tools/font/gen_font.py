#!/usr/bin/env python3
"""Render Noto Sans Bold ASCII 32..126 into src/launcher_font.h (8-bit alpha).

    tools/font/gen_font.py [/path/to/NotoSans-Bold.ttf]

Noto Sans is under the SIL Open Font License 1.1, which allows embedding
the rendered glyphs; the notice goes into the header.
"""
import os, subprocess, sys, tempfile
font = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/noto/NotoSans-Bold.ttf'
H = 32
out = os.path.join(os.path.dirname(__file__), '../../src/launcher_font.h')
glyphs = []
with tempfile.TemporaryDirectory() as td:
    for c in range(32, 127):
        ch = chr(c)
        p = os.path.join(td, f'{c}.gray')
        # A fixed-height canvas: render "|" + ch + "|" style metrics by using
        # -gravity and a fixed size; width from the advance via -trim off.
        txt = ch if ch not in ('\\', '%', '@') else '\\' + ch
        if ch == ' ':
            w = H // 4
            glyphs.append((w, bytes(w * H)))
            continue
        cmd = ['magick', '-background', 'black', '-fill', 'white', '-font', font,
               '-pointsize', str(int(H * 0.72)), f'label:{txt}',
               '-gravity', 'center', '-extent', f'x{H}', '-depth', '8', f'gray:{p}']
        subprocess.run(cmd, check=True)
        data = open(p, 'rb').read()
        w = len(data) // H
        glyphs.append((w, data[:w * H]))
with open(out, 'w') as f:
    f.write('/* Generated by tools/font/gen_font.py from Noto Sans Bold.\n'
            ' * Noto Sans: Copyright 2022 The Noto Project Authors, SIL Open Font\n'
            ' * License 1.1 (https://openfontlicense.org). 8-bit coverage, ASCII. */\n')
    f.write('#ifndef LAUNCHER_FONT_H\n#define LAUNCHER_FONT_H\n#include <stdint.h>\n')
    f.write(f'#define LAUNCHER_FONT_H_PX {H}\n')
    f.write('static const uint8_t launcher_font_w[95] = {' + ','.join(str(w) for w, _ in glyphs) + '};\n')
    offs, o = [], 0
    for w, _ in glyphs:
        offs.append(o); o += w * H
    f.write('static const uint32_t launcher_font_off[95] = {' + ','.join(map(str, offs)) + '};\n')
    blob = b''.join(d for _, d in glyphs)
    f.write(f'static const uint8_t launcher_font_px[{len(blob)}] = {{\n')
    for i in range(0, len(blob), 32):
        f.write(','.join(str(b) for b in blob[i:i + 32]) + ',\n')
    f.write('};\n#endif\n')
print('wrote', out, len(glyphs), 'glyphs')
